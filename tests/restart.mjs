assert.equal(r.phase, 'lobby');
assert.equal(r.round, 2);
assert.equal(r.code, 'ABCDEFGH');
assert.equal(r.duration, 900);
assert.equal(r.projects.length, 0);
assert.equal(r.time, 0);
assert.equal(r.counter, 0);
assert.equal(new Set(r.pool).size, 300);
assert.deepEqual(r.processed, ['previous-request']);
const fresh = makeRoom('x', 'y');
addTeam(fresh, 'a', 'key-a', 'A');
assert.deepEqual(r.teams[0], fresh.teams[0]);
assert.equal(view(r, 'key-a').me.id, 'a');
assert.equal(view(r, 'host').host, true);
assert.throws(() => action(r, 'host', { type: 'start', round: 1 }), /新一局/);
r.onboardingVersion = 0;
action(r, 'host', { type: 'start', round: 2 }, 2000);
