action(r, 'host', { type: 'start' }, -119000);
tick(r, 1000);
action(r, 'key-a', { type: 'loan' });
action(r, 'key-a', { type: 'upgrade', kind: 'cost' });
action(r, 'host', { type: 'end' });
assert.throws(() => action(r, 'key-a', { type: 'restart' }), /主持人/);
